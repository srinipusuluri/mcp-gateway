import { useEffect, useState } from "react";
import { api, fmtMs, HttpError } from "../api";
import type { Me } from "../App";
import { Badge, Card, CopyButton, Empty, ErrorNote, Field, JsonView, Stat, TabPanel, Tabs } from "../components";

interface Workflow { id: string; title: string; description: string; requires: string[]; usesMockOnly: boolean; code: string }
interface Outcome {
  ok: boolean; result?: unknown; error?: { code: string; message: string; approvalId?: string }; logs: string[]; pendingApprovals: string[];
  trace: Array<{ seq: number; tool: string; kind: string; durationMs: number; ok: boolean; error?: string; recordsReturned?: number; salesforceApiCalls: number; redactions: number }>;
  metadata: { executionId: string; mode: "mock" | "live"; durationMs: number; toolCalls: number; salesforceApiCalls: number; recordsReturned: number; redactions: number; resultBytes: number; truncated: boolean; runtime: string };
}

export function Playground({ me, goSecurity }: { me: Me; goSecurity: () => void }) {
  const [workflows, setWorkflows] = useState<Workflow[]>([]);
  const [task, setTask] = useState("Give me an account 360 for Acme Corporation");
  const [code, setCode] = useState("");
  const [genInfo, setGenInfo] = useState<string | null>(null);
  const [out, setOut] = useState<Outcome | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState<"gen" | "run" | null>(null);
  const [tab, setTab] = useState<"result" | "trace" | "logs">("result");
  const canExecute = me.permissions.includes("execute") || me.permissions.includes("admin");

  useEffect(() => {
    api<{ workflows: Workflow[] }>("/api/workflows").then((r) => setWorkflows(r.workflows)).catch(() => undefined);
  }, []);

  const generate = async (workflowId?: string) => {
    setBusy("gen"); setError(null); setGenInfo(null);
    try {
      const r = await api<{ code: string | null; generator: string; message?: string; workflowId?: string; model?: string; usage?: { inputTokens: number; outputTokens: number } }>("/api/playground/generate", { body: { task: task.trim().length >= 3 ? task : "workflow", workflowId } });
      if (r.code) {
        setCode(r.code);
        setOut(null);
      }
      setGenInfo(r.code ? `Generated by ${r.generator === "claude" ? `Claude (${r.model})` : `built-in template${r.workflowId ? ` “${r.workflowId}”` : ""}`}${r.usage ? ` · ${r.usage.inputTokens} in / ${r.usage.outputTokens} out tokens` : ""}. Review before running.` : (r.message ?? "No code generated."));
    } catch (e) { setError(e instanceof HttpError ? e.message : "Generation failed"); }
    finally { setBusy(null); }
  };

  const execute = async () => {
    setBusy("run"); setError(null);
    try { const r = await api<Outcome>("/api/execute", { body: { code } }); setOut(r); setTab(r.ok ? "result" : "result"); }
    catch (e) { setError(e instanceof HttpError ? e.message : "Execution failed"); }
    finally { setBusy(null); }
  };

  const maxMs = Math.max(1, ...(out?.trace.map((t) => t.durationMs) ?? [1]));

  return (
    <>
      <div className="topbar"><div><h1>Code Mode Playground</h1><div className="sub">Describe a task, review the generated TypeScript, execute it in the sandbox</div></div></div>
      <div className="grid cols-2">
        <Card title="1 · Task">
          <Field label="Natural-language task">{(id) => <textarea id={id} rows={3} value={task} onChange={(e) => setTask(e.target.value)} />}</Field>
          <div className="row">
            <button className="btn btn-primary" disabled={busy !== null} onClick={() => void generate()}>{busy === "gen" ? "Generating…" : "Generate TypeScript"}</button>
          </div>
          <Field label="…or start from a demonstration workflow" hint="All ten are ready-made Code Mode programs">
            {(id) => (
              <select id={id} defaultValue="" onChange={(e) => { const w = workflows.find((x) => x.id === e.target.value); if (w) { setCode(w.code); setTask(w.description); setOut(null); setGenInfo(`Loaded workflow “${w.title}”${w.usesMockOnly ? " (uses mock-only adapters)" : ""}.`); } }}>
                <option value="" disabled>Choose a workflow…</option>
                {workflows.map((w) => <option key={w.id} value={w.id}>{w.title}{w.usesMockOnly ? " (mock adapters)" : ""}</option>)}
              </select>
            )}
          </Field>
          {genInfo && <div className="note note-info" role="status">{genInfo}</div>}
        </Card>
        <Card title="2 · Review &amp; execute" actions={code ? <CopyButton text={code} /> : null}>
          <Field label="Generated TypeScript (editable)" hint="Runs in an isolated sandbox with only the sf.* / netsuite.* APIs you are authorized for.">
            {(id) => <textarea id={id} className="mono" rows={16} value={code} onChange={(e) => setCode(e.target.value)} spellCheck={false} placeholder="async () => { … }" />}
          </Field>
          <div className="row">
            <button className="btn btn-primary" disabled={busy !== null || !code.trim() || !canExecute} onClick={() => void execute()}>{busy === "run" ? "Executing…" : "Execute"}</button>
            {!canExecute && <span style={{ color: "var(--muted)", fontSize: 13 }}>Your role lacks the “execute” permission.</span>}
          </div>
        </Card>
      </div>
      <ErrorNote error={error} />

      <Card title="3 · Results" className="" >
        {!out ? <Empty>Run a program to see structured results and the execution trace.</Empty> : (
          <div aria-live="polite">
            <div className="row" style={{ marginBottom: 12 }}>
              <Badge tone={out.ok ? "good" : "bad"}>{out.ok ? "success" : out.error?.code}</Badge>
              <Badge tone={out.metadata.mode === "mock" ? "mock" : "info"} title="Where the data came from">{out.metadata.mode === "mock" ? "MOCK execution" : "LIVE Salesforce"}</Badge>
              <Badge>{out.metadata.runtime}</Badge>
              <code style={{ color: "var(--muted)" }}>{out.metadata.executionId}</code>
            </div>
            <div className="grid cols-4" style={{ marginBottom: 12 }}>
              <Stat label="Duration" value={fmtMs(out.metadata.durationMs)} />
              <Stat label="Tool calls" value={out.metadata.toolCalls} hint={`${out.metadata.recordsReturned} records`} />
              <Stat label="SF API calls" value={out.metadata.salesforceApiCalls} />
              <Stat label="Redactions" value={out.metadata.redactions} hint={out.metadata.truncated ? "result truncated" : `${out.metadata.resultBytes} B`} />
            </div>
            {!out.ok && out.error && (
              <div className={`note ${out.error.code === "approval_required" ? "note-warn" : "note-bad"}`} role="alert">
                <strong>{out.error.code}</strong>: {out.error.message}
                {out.pendingApprovals.length > 0 && <div className="row" style={{ marginTop: 8 }}><button className="btn btn-sm" onClick={goSecurity}>Open approval queue</button><span>After an approver approves, press Execute again.</span></div>}
              </div>
            )}
            <Tabs label="Result views" value={tab} onChange={setTab} tabs={[{ id: "result", label: "Result" }, { id: "trace", label: "Execution trace", badge: out.trace.length }, { id: "logs", label: "Logs", badge: out.logs.length || undefined }]} />
            {tab === "result" && <TabPanel id="result">{out.ok ? <JsonView value={out.result} maxHeight={420} /> : <Empty>No result — see the error above.</Empty>}</TabPanel>}
            {tab === "trace" && (
              <TabPanel id="trace">
                <div className="table-wrap"><table>
                  <caption>Every host call made by your program, in order</caption>
                  <thead><tr><th>#</th><th>Tool</th><th>Kind</th><th>Timeline</th><th className="num">ms</th><th className="num">Rows</th><th className="num">SF calls</th><th>Status</th></tr></thead>
                  <tbody>{out.trace.map((t) => (
                    <tr key={t.seq}>
                      <td>{t.seq}</td><td><code>{t.tool}</code></td><td>{t.kind}</td>
                      <td style={{ minWidth: 160 }}><div className="wf-track" aria-hidden="true"><div className={`wf-fill ${t.ok ? "" : "bad"}`} style={{ width: `${(t.durationMs / maxMs) * 100}%` }} /></div></td>
                      <td className="num">{Math.round(t.durationMs)}</td><td className="num">{t.recordsReturned ?? "–"}</td><td className="num">{t.salesforceApiCalls}</td>
                      <td>{t.ok ? <Badge tone="good">ok</Badge> : <Badge tone="bad">{t.error}</Badge>}</td>
                    </tr>))}</tbody>
                </table></div>
              </TabPanel>
            )}
            {tab === "logs" && <TabPanel id="logs">{out.logs.length ? <JsonView value={out.logs.join("\n")} /> : <Empty>The program wrote no console output.</Empty>}</TabPanel>}
          </div>
        )}
      </Card>
    </>
  );
}

/** Regenerates examples/ from the single source of truth (WORKFLOWS + the tool registry). `npm run examples:generate` */
import { mkdirSync, writeFileSync } from "node:fs";
import { createSalesforceRegistry, WORKFLOWS } from "../packages/salesforce-mcp/src";
import { generateTypeScriptApi } from "../packages/tool-registry/src";

const DIRS: Record<string, string> = {
  "account-360": "account-360",
  "sales-pipeline": "sales-pipeline",
  "customer-risk": "customer-risk",
  "service-intelligence": "service-intelligence",
  "cross-system-analysis": "cross-system-analysis",
};

writeFileSync("examples/sf-api.d.ts", `// GENERATED by scripts/generate-examples.ts from the tool registry. Do not edit.\n// Ambient declarations of the sandbox globals so example programs are type-checked.\n${generateTypeScriptApi(createSalesforceRegistry().list())}\n`);

for (const w of WORKFLOWS) {
  const dir = DIRS[w.id] ? `examples/${DIRS[w.id]}` : "examples/more";
  mkdirSync(dir, { recursive: true });
  const file = DIRS[w.id] ? `${dir}/program.ts` : `${dir}/${w.id}.ts`;
  writeFileSync(file, `// GENERATED from packages/salesforce-mcp/src/workflows.ts (${w.id}). Do not edit.\n// This is the exact program a model would pass to execute_code.\n${w.build(w.defaults)};\n\nexport {};\n`);
  if (DIRS[w.id]) {
    writeFileSync(
      `${dir}/README.md`,
      `# ${w.title}\n\n${w.description}\n\n- Requires permissions: ${w.requires.map((r) => `\`${r}\``).join(", ")}\n- Uses mock-only adapters: ${w.usesMockOnly ? "yes (live adapter needed for a real org)" : "no (works against a live org)"}\n\nRun it against the mock org:\n\n\`\`\`bash\nnpm run example -- ${w.id}\n\`\`\`\n\nOr paste \`program.ts\` into the dashboard Playground, or send it to the \`execute_code\` MCP tool.\n`,
    );
  }
}
console.log("examples regenerated");
